-- Migration V005: Convert Content, Comment, Reason columns to NVARCHAR to preserve Vietnamese diacritics
IF EXISTS (SELECT 1 FROM INFORMATION_SCHEMA.COLUMNS WHERE TABLE_NAME = 'Notifications' AND COLUMN_NAME = 'Content' AND DATA_TYPE = 'varchar')
BEGIN
    ALTER TABLE Notifications ALTER COLUMN Content NVARCHAR(MAX) NOT NULL;
END
GO

IF EXISTS (SELECT 1 FROM INFORMATION_SCHEMA.COLUMNS WHERE TABLE_NAME = 'Reviews' AND COLUMN_NAME = 'Comment' AND DATA_TYPE = 'varchar')
BEGIN
    ALTER TABLE Reviews ALTER COLUMN Comment NVARCHAR(MAX) NULL;
END
GO

IF EXISTS (SELECT 1 FROM INFORMATION_SCHEMA.COLUMNS WHERE TABLE_NAME = 'ReturnRequests' AND COLUMN_NAME = 'Reason' AND DATA_TYPE = 'varchar')
BEGIN
    ALTER TABLE ReturnRequests ALTER COLUMN Reason NVARCHAR(MAX) NULL;
END
GO
